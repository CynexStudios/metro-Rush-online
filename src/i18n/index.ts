const REFERENCE_KEYS = Object.keys(ES);

/**
 * Computes real translation coverage mathematically against the full reference keyset (`ES`).
 * Never returns inflated or simulated percentages.
 */
export function getLanguageCoveragePercent(lang: LanguageCode): number {
  const dict = DICTIONARIES[lang];
  if (!dict || REFERENCE_KEYS.length === 0) return 0;
  let count = 0;
  for (const key of REFERENCE_KEYS) {
    if (typeof dict[key] === 'string' && dict[key].trim().length > 0) {
      count += 1;
    }
  }
  return Math.round((count / REFERENCE_KEYS.length) * 100);
}

/**
 * Only expose 100%-complete languages inside Settings language selector (§22.5).
 */
export const SELECTABLE_LANGUAGES = SUPPORTED_LANGUAGES.filter(
  (l) => getLanguageCoveragePercent(l.code) === 100,
);

export function t(
  lang: LanguageCode,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const dict = DICTIONARIES[lang] ?? ES;
  let text = dict[key] ?? ES[key] ?? EN[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}

export function getCityLabel(lang: LanguageCode, id: DistrictId): { name: string; sub: string } {
  return {
    name: t(lang, `city.${id}.name`),
    sub: t(lang, `city.${id}.sub`),
  };
}

export function getModeLabel(lang: LanguageCode, mode: GameMode): { label: string; desc: string } {
  return {
    label: t(lang, `mode.${mode}`),
    desc: t(lang, `mode.${mode}.desc`),
  };
}

export function getTimeLabel(lang: LanguageCode, period: TimeOfDay): string {
  return t(lang, `time.${period}`);
}
