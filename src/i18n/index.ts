const DICTIONARIES: Record<LanguageCode, Dict> = {
  es: ES,
  en: EN,
  fr: FR,
  pt: PT,
  de: DE,
  it: IT,
  ja: JA,
  ko: KO,
  zh: ZH,
  ru: RU,
};

export function t(
  lang: LanguageCode,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const dict = DICTIONARIES[lang] ?? ES;
  let text = dict[key] ?? EN[key] ?? ES[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}

export function getCityLabel(lang: LanguageCode, id: DistrictId): { name: string; sub: string } {
  return {
    name: t(lang, `city.${id}.name`),
    sub: t(lang, `city.${id}.sub`),
  };
}

export function getModeLabel(lang: LanguageCode, mode: GameMode): { label: string; desc: string } {
  return {
    label: t(lang, `mode.${mode}`),
    desc: t(lang, `mode.${mode}.desc`),
  };
}

export function getTimeLabel(lang: LanguageCode, period: TimeOfDay): string {
  return t(lang, `time.${period}`);
}
